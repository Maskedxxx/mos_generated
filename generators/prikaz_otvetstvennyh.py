ROLE_FIELDS = {"director": "signer_fio", "resp1": "resp1", "resp2": "resp2", "resp3": "resp3", "resp4": "resp4"}

_MONTHS = {"января": 1, "февраля": 2, "марта": 3, "апреля": 4, "мая": 5, "июня": 6, "июля": 7,
           "августа": 8, "сентября": 9, "октября": 10, "ноября": 11, "декабря": 12}
_UP, _LO = "А-ЯЁ", "а-яё"
_SURNAME = rf"[{_UP}][{_LO}]+(?:-[{_UP}][{_LO}]+)?"
# Три написания ФИО: «Фамилия И.О.», «И.О. Фамилия», «Фамилия Имя Отчество» (отчество на -ич / -вна / -ична;
# просто «-на» ловило женские имена: «Директор Смирнова Анна Павловна» → «Директор Смирнова Анна»)
_FIO_PATTERNS = [
    (re.compile(rf"({_SURNAME})\s+([{_UP}])\.\s?([{_UP}])\."), lambda m: (m[1], m[2], m[3])),
    (re.compile(rf"(?<![{_UP}{_LO}])([{_UP}])\.\s?([{_UP}])\.\s?({_SURNAME})"), lambda m: (m[3], m[1], m[2])),
    (re.compile(rf"({_SURNAME})\s+([{_UP}])[{_LO}]+\s+([{_UP}])[{_LO}]+(?:ич|вна|ична)\b"), lambda m: (m[1], m[2], m[3])),
]


def parse_start_date(text: str) -> date:
    """
    Дата старта из поля формы: «29» апреля 2026 г. / 29 апреля 2026 / 29.04.2026 (кавычки и «г.» допускаются).
    Нераспознанная дата → ValueError (срок в плане не может быть угадан).
    """
    t = re.sub(r"[«»\"'“”„]", " ", str(text or "")).lower()
    m = re.search(r"\b(\d{1,2})\.(\d{1,2})\.(\d{4})\b", t)
    if m:
        return date(int(m[3]), int(m[2]), int(m[1]))
    m = re.search(r"\b(\d{1,2})\s+([а-яё]+)\s+(\d{4})", t)
    if m and m[2] in _MONTHS:
        return date(int(m[3]), _MONTHS[m[2]], int(m[1]))
    raise ValueError(f"Дата начала мероприятий не распознана: «{text}». Укажите в виде «29» апреля 2026 г. или 29.04.2026")


# Слова должностей с заглавной буквы, которые шаблоны ФИО могут принять за фамилию («Директор С.С. Сидоров»)
_POSITION_WORDS = {
    "директор", "генеральный", "исполнительный", "коммерческий", "технический", "финансовый", "главный", "ведущий",
    "старший", "начальник", "заместитель", "руководитель", "инженер", "мастер", "менеджер", "специалист", "экономист",
    "бухгалтер", "технолог", "механик", "администратор", "кладовщик", "оператор", "аналитик", "президент", "председатель",
}


def _find_fio(text: str):
    """
    ФИО в свободном тексте: (начало, конец, (фамилия, И, О)) первого по позиции из трёх написаний или None.
    Совпадение, где «фамилия» — слово должности, пропускается и ищется следующее: «Директор Иван Иванович Петров»
    не даёт «Директор И.И.». Если «Фамилия И.О.» и «И.О. Фамилия» делят одни инициалы, отбрасывается вариант
    с должностью: «Директор С.С. Сидоров» → «С.С. Сидоров», «Иванов И.И. Генеральный директор» → «Иванов И.И.».
    """
    t = str(text or "")
    is_post = lambda k, m: _FIO_PATTERNS[k][1](m)[0].lower() in _POSITION_WORDS
    found = {}
    for k, (rx, _) in enumerate(_FIO_PATTERNS):
        m = next((m for m in rx.finditer(t) if not is_post(k, m)), None)
        if m:
            found[k] = m
    if not found:
        return None
    if 0 in found and 1 in found and found[1].start() < found[0].end():
        found.pop(1)   # оба без слова должности — как раньше, «Фамилия И.О.»
    k, m = min(found.items(), key=lambda km: km[1].start())
    return m.start(), m.end(), _FIO_PATTERNS[k][1](m)


def short_fio(text: str) -> str | None:
    """ФИО из свободного текста поля («должность, ФИО, тел., почта») → «Фамилия И.О.»; первое по позиции; нет — None."""
    hit = _find_fio(text)
    if not hit:
        return None
    surname, i, o = hit[2]
    return f"{surname} {i}.{o}."


def split_person(text: str) -> tuple[str, str]:
    """
    Поле «должность, ФИО, тел., почта» → (ФИО, как написано; остальное — должность, телефон, почта).
    ФИО — первое по позиции из трёх написаний (_FIO_PATTERNS); не найдено — ("", весь текст).
    """
    t = str(text or "").strip()
    hit = _find_fio(t)
    if not hit:
        return "", t
    a, b = hit[0], hit[1]
    # на месте ФИО: у левой части срезаем хвостовые разделители, у правой — ведущие, части соединяем через «, »;
    # затем убираем пустые и непарные скобки, повторы разделителей и лишние пробелы
    left, right = t[:a].rstrip(" ,;:–—-(").strip(), t[b:].lstrip(" ,;:–—-)").strip()
    rest = ", ".join(x for x in (left, right) if x)
    rest = re.sub(r"\(\s*\)", "", rest)
    if rest.count("(") != rest.count(")"):
        rest = rest.replace("(", "").replace(")", "")
    rest = re.sub(r"\s*([,;])\s*(?:[,;]\s*)+", r"\1 ", rest)
    rest = re.sub(r"\s{2,}", " ", re.sub(r"\s+([,;])", r"\1", rest)).strip(" ,;–—-")
    # первая буква — заглавная, как в образцах; e-mail в начале не трогаем
    if "@" not in rest.split(",")[0]:
        rest = rest[:1].upper() + rest[1:]
    return t[a:b], rest
