# Роль → поле формы, из которого берётся ФИО ответственного
ROLE_FIELDS = {"director": "signer_fio", "resp1": "resp1", "resp2": "resp2", "resp3": "resp3", "resp4": "resp4"}

_MONTHS = {"января": 1, "февраля": 2, "марта": 3, "апреля": 4, "мая": 5, "июня": 6, "июля": 7,
           "августа": 8, "сентября": 9, "октября": 10, "ноября": 11, "декабря": 12}
_UP, _LO = "А-ЯЁ", "а-яё"
_SURNAME = rf"[{_UP}][{_LO}]+(?:-[{_UP}][{_LO}]+)?"
# Три написания ФИО: «Фамилия И.О.», «И.О. Фамилия», «Фамилия Имя Отчество» (отчество на -ич / -на)
_FIO_PATTERNS = [
    (re.compile(rf"({_SURNAME})\s+([{_UP}])\.\s?([{_UP}])\."), lambda m: (m[1], m[2], m[3])),
    (re.compile(rf"(?<![{_UP}{_LO}])([{_UP}])\.\s?([{_UP}])\.\s?({_SURNAME})"), lambda m: (m[3], m[1], m[2])),
    (re.compile(rf"({_SURNAME})\s+([{_UP}])[{_LO}]+\s+([{_UP}])[{_LO}]+(?:ич|на)\b"), lambda m: (m[1], m[2], m[3])),
]


def parse_start_date(text: str) -> date:
    """
    Дата старта из поля формы: «29» апреля 2026 г. / 29 апреля 2026 / 29.04.2026 (кавычки и «г.» допускаются).
    Нераспознанная дата → ValueError (срок в плане не может быть угадан).
    """
    t = re.sub(r"[«»\"'“”„]", " ", str(text or "")).lower()
    m = re.search(r"\b(\d{1,2})\.(\d{1,2})\.(\d{4})\b", t)
    if m:
        return date(int(m[3]), int(m[2]), int(m[1]))
    m = re.search(r"\b(\d{1,2})\s+([а-яё]+)\s+(\d{4})", t)
    if m and m[2] in _MONTHS:
        return date(int(m[3]), _MONTHS[m[2]], int(m[1]))
    raise ValueError(f"Дата начала мероприятий не распознана: «{text}». Укажите в виде «29» апреля 2026 г. или 29.04.2026")


def short_fio(text: str) -> str | None:
    """ФИО из свободного текста поля («должность, ФИО, тел., почта») → «Фамилия И.О.»; первое по позиции; нет — None."""
    found = []
    for rx, parts in _FIO_PATTERNS:
        m = rx.search(str(text or ""))
        if m:
            found.append((m.start(), parts(m)))
    if not found:
        return None
    surname, i, o = min(found)[1]
    return f"{surname} {i}.{o}."
